package com.ibm.plugin.rules.detection;

import static org.assertj.core.api.Assertions.assertThat;

import com.ibm.engine.detection.DetectionStore;
import com.ibm.engine.model.IValue;
import com.ibm.mapper.model.INode;
import com.ibm.plugin.CxxVerifier;
import com.ibm.plugin.TestBase;
import com.sonar.cxx.sslr.api.AstNode;
import com.sonar.cxx.sslr.api.Grammar;
import java.util.ArrayList;
import java.util.List;
import javax.annotation.Nonnull;
import org.junit.jupiter.api.Test;
import org.sonar.cxx.squidbridge.SquidAstVisitorContext;
import org.sonar.cxx.squidbridge.api.Symbol;
import org.sonar.cxx.squidbridge.checks.SquidCheck;

/**
 * A chain such as {@code library.digests("default").EVP_get_digestbyname("SHA512")} is detected as
 * its last call, with that call's arguments.
 */
class CxxChainedCallTest extends TestBase {

    private final List<String> values = new ArrayList<>();

    @Test
    void test() {
        CxxVerifier.verify("rules/detection/CxxChainedCallTestFile.cc", this);
        assertThat(values).containsExactly("SHA-512");
    }

    @Override
    public void asserts(
            int findingId,
            @Nonnull
                    DetectionStore<
                                    SquidCheck<?>,
                                    AstNode,
                                    Symbol,
                                    SquidAstVisitorContext<? extends Grammar>>
                            detectionStore,
            @Nonnull List<INode> nodes) {
        detectionStore.getDetectionValues().stream().map(IValue::asString).forEach(values::add);
    }
}
